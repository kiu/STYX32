"""3D models for the 1.27 mm STYX32 headers (run with FreeCAD's freecadcmd.exe):
  "C:\\Program Files\\FreeCAD 1.1\\bin\\freecadcmd.exe" lib/tools/make_3d.py

Geometry as in Kiu's Connector_IDC_127/make_3d.py, from the HANXIA datasheets
"HX JN1.27-2xN TP H4.9" (SMD) and "HX JN1.27-2xNP ZZ H4.9" (THT): body 5.0 wide,
length = (N-1)*1.27 + 1.27 + 6.3, walls 0.8, key slot 2.45 wide on the pin 1 side,
pins 0.4 square on a 1.27 grid. SMD: housing on 0.3 leads, lead tips 5.8 apart.
THT: housing 4.9 high on the board, pin tails 2.3 below the board (datasheet C42372545).
Writes lib/STYX32.3dshapes/IDC-Header_2xNN_P1.27mm_Vertical_{SMD,THT}.{step,wrl}.
"""
import os
import sys

import FreeCAD as App
import Part

PITCH = 1.27
W, WALL, END_WALL = 5.0, 0.8, 0.8
HOUSING = 4.9
FLOOR = 1.2
KEY_W = 2.45
PIN = 0.4
LEAD_T = 0.3
LEAD_SPAN = 5.8
TAIL = 2.3
BODY_RGB = (0.12, 0.12, 0.13)
PIN_RGB = (0.85, 0.75, 0.35)

HERE = os.path.dirname(os.path.abspath(sys.argv[-1] if sys.argv[-1].endswith(".py") else __file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "STYX32.3dshapes"))
V = App.Vector


def header(n_rows, tht):
    span = (n_rows - 1) * PITCH
    length = span + PITCH + 6.3
    z0 = 0.0 if tht else LEAD_T
    top = z0 + HOUSING
    body = Part.makeBox(W, length, HOUSING, V(-W / 2, -length / 2, z0))
    cav = Part.makeBox(W - 2 * WALL, length - 2 * END_WALL, HOUSING, V(-W / 2 + WALL, -length / 2 + END_WALL, z0 + FLOOR))
    key = Part.makeBox(WALL + 0.2, KEY_W, HOUSING, V(-W / 2 - 0.1, -KEY_W / 2, z0 + FLOOR))
    body = body.cut(cav).cut(key)
    # pin 1 corner chamfer on top (model +y = footprint -y = pin 1 end)
    cut = Part.makeBox(1.0, 1.0, 0.4, V(-W / 2 - 0.5, length / 2 - 0.5, top - 0.3))
    cut.rotate(V(-W / 2, length / 2, top), V(0, 0, 1), 45)
    body = body.cut(cut)
    pins = []
    pin_top = top - 0.6
    for i in range(n_rows):
        y = -span / 2 + i * PITCH
        for side in (-1, 1):
            x = side * PITCH / 2
            if tht:
                pins.append(Part.makeBox(PIN, PIN, pin_top + TAIL, V(x - PIN / 2, y - PIN / 2, -TAIL)))
            else:
                pins.append(Part.makeBox(PIN, PIN, pin_top, V(x - PIN / 2, y - PIN / 2, 0)))
                x0, x1 = (-LEAD_SPAN / 2, x + PIN / 2) if side < 0 else (x - PIN / 2, LEAD_SPAN / 2)
                pins.append(Part.makeBox(x1 - x0, PIN, LEAD_T, V(x0, y - PIN / 2, 0)))
    return body.removeSplitter(), pins[0].fuse(pins[1:]).removeSplitter()


def wrl(path, parts):
    out = ["#VRML V2.0 utf8", "# generated by make_3d.py, units 0.1 inch (KiCad convention)"]
    for shape, rgb in parts:
        pts, tris = shape.tessellate(0.05)
        out.append("Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f "
                   "specularColor 0.2 0.2 0.2 shininess 0.3 } }" % rgb)
        out.append(" geometry IndexedFaceSet { coord Coordinate { point [")
        out.append(",".join("%.5f %.5f %.5f" % (p.x / 2.54, p.y / 2.54, p.z / 2.54) for p in pts))
        out.append("] } coordIndex [" + ",".join("%d,%d,%d,-1" % t for t in tris) + "] } }")
    open(path, "w").write("\n".join(out) + "\n")


os.makedirs(OUT, exist_ok=True)
for n in (3, 4, 5):
    for tht in (False, True):
        name = "IDC-Header_2x%02d_P1.27mm_Vertical_%s" % (n, "THT" if tht else "SMD")
        body, pins = header(n, tht)
        Part.makeCompound([body, pins]).exportStep(os.path.join(OUT, name + ".step"))
        wrl(os.path.join(OUT, name + ".wrl"), [(body, BODY_RGB), (pins, PIN_RGB)])
        print("RESULT", name, "valid", body.isValid() and pins.isValid())
